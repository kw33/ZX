BORDCR equ 23624

;----------------------------------------------
startload:

    ld ix,#8000 ; 32768              ;30000 ; #7530
nulling:
    ld (ix),0
    inc ix
    defb #DD ; IX
    ld a,h   ; IXh
    cp #90
    jr nz,nulling


    ld ix,#8000 ; 32768
    ld hl,22	; длина заголовка
    call load


    ld ix,#4000 ; 16384
    ld hl,#3300 ; длина - экран
    call load
    ; проверяем флаги
    ret c ; ok
    ld a,6 ; жёлто
    out (#FE),a
    ret z ; error
    ; ZF=0
    ld a,1 ; синё
    out (#FE),a ; break
    ret

;----------------------------------------------
begin_of_block:

;===============================================================================
; IX  - куда сохраняем
; HL  - количество байтов

; используются внутри:
; DE' - цвета поребрика
; C'  - CRC
; HL' - счетчик длины
; CRC - всего-то контрольная сумма, с помощью XOR

load:
    di
    exx ; теперь HL стал HL' (как и BC DE)
    push hl ; cохранили системный HL'
    ld a,(BORDCR)
    rrca
    rrca
    rrca
    push af ; сохранили цвет исходного поребрика
.waitpilot:
    ; при начальном ожидании пилота - не полосим
    pop af  ; взяли
    push af ; вернули
    exx
    ld d,a
    ld e,a ; одинаковые цвета, равны системному поребрику
    ld c,0 ; до кучи обнулим CRC
    exx
    ld e,255 ; периодов пилота
.cnt:
    ; прожуём отрицательный импульс
    call measu_n
    jr nc,.nc1 ;                                         не надо ? ? ?
      ;ld (ix),a
      ;inc ix ; CF not changed
    ; будем контролировать положительный
    call measu_p
    jr nc,.nc1
      ;ld (ix),a
      ;inc ix ; CF not changed
    cp 48 ; минимум для пилота, максимум и так ограничен
    jr c,.firstbyte
    dec e
    jr nz,.cnt
    ; cчётчик обнулился, сделаем =1
    inc e
    ; считаны все начальные пилоты, полосим
    exx
    ld de,#0105 ; p n  цвета поребрика
    exx
    jr .cnt

.firstbyte:
    dec e ; был ли счётчик=1 ?
    jr nz,.waitpilot ; рано данные пришли

    ; далее получаем байты                     /////////////////////////////////
    ; a -  длит-сть имп-са  ; d свободно тут
		   ; прокручивая, будем получать то 1, то 0 в CF
    ld e,%10101010 ; флаг для счёта полубайтов
    ld l,0
    ; в h храним старший полубайт принимаемых данных
    ; в l - контрольную сумму
    jr .enter

    ;============================================================ errors:
.nc1:
	jr z,.waitpilot ; over/under
	; break Z=0, C=0
.exit:	; CF=1-ok, {CF=0-break/error, а ZF = 0-break, 1-error}
	pop bc ; (af) восстановили цвет исходного поребрика  не изменяя флаг
	ld a,b
	out (254),a
	ld iy,5C3Ah ; на всякий=)
	pop hl
	exx ; восстановили системный HL'
	ei     ;;; EI
	ret

    ;============================================================ errors end

.quants:
    call measu_p ; положительный
    jr nc,.exit ; err / break

.enter:
 ;     ld (ix),a     ; 1111 импульс
 ;     inc ix

    ; преобразовать длительность в id импульса
    ; a - длительность импульса
    and %111000 ; шесть длин импульсов, синхро-импульс сюда приходить не должен!
    rrca
    rrca
    rrca
 ;        ld (ix),a
 ;        inc ix
    ; a - id импульса (0..5)  (положительного)
    ; сохранить id импульса
    ld d,a ; d - id полож.импульса

    ; мерим длительность отрицательного импульса
    call measu_n
    jr nc,.exit ; err / break
 ;        ld (ix),a     ; 0000 импульс
 ;        inc ix
    ; преобразовать длительность в id импульса
    ; a - длительность импульса
    and %111000 ; шесть длин импульсов, синхро-импульс сюда приходить не должен!
    rrca
    rrca
    rrca
 ;        ld (ix),a
 ;        inc ix
    ; d и a - id импульса (0..5)  (положительного и отрицательного)
    ; d a вместе - это период определяющий 4 бита
    cp d
    jr z,.done ; если одинаковые - 0000..0101, d=a = искомое число
    jr nc,.n6_10 ; если a>d(d<a), то 0110..1010 (6..10) [короче|длиннeе]
    ; d>a - 1101..1111 (11..15)    a=0..4 переделываем в 15..11
    xor %1111
    jr .done
.n6_10:
    ld a,6  ; для d < a
    add a,d
.done:
    ; готово а - число (4 бита)
    rlc e
    jr nc,.secondhalf ; в а второй полубайт
    ; в а первый полубайт
    rlca
    rlca
    rlca
    rlca
    ld h,a     ; сохранили
    jr .quants
.secondhalf:
    or a,h     ; добавили ко второму первый
    ;ld b,a    ; собрали байт, cохранили в b

    ex af,af'
    exx
    ld a,h
    or l
    jr z,.finish ; был получен байт crc
    ; уменьшаем после проверки на 0, т.к. нужно получить ещё байт crc
    dec hl
    ex af,af'  ; вернули байт
    ld (ix),a  ; сохранить байт
    inc ix
    ; считать CRC и проверить, всё ли
    xor c
    ld c,a ; можно в b сохранить если надо
    exx
    jr .quants ;////////////////////////////////////////////////////////////////
    ;
.finish:
    ex af,af' ; вернули считанный с ленты crc
    xor c     ; равны ли полученный и рассчитанный crc
    exx       ; ?                                                    ? ? ?
    jr z,.ok
    ; error - CF=0,ZF=1 надо сделать
    xor a
    jr .exit
.ok:
    ; ok - CF=1
    scf
    jr .exit
    ;---------------------------------------------------------------------------



;$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$
;$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$
; measu - измерять продолжительность                  изменяются a b c
; отсчёт ведётся от COUNTMIN до 255
; валидный импульс включает в себя и импульс пилот-тона
; (если насчитало более 255 - слишком длинный импульс: over)
; после отсчёта вычетается COUNTMIN + PERIODMIN
; если получилось отрицательное - слишком короткий импульс: under
; b = 0 - измеряем отрицательный импульс (ear уже в нуле)
; b = %01000000 (64 = EARBIT) - измеряем положительный имп-с (ear уже в единице)
; a - цвет поребрика
; выход:
; a - длительность импульса (если она валидная, т.е. CF=1, ZF=0)
; break - CF=0, ZF=0 (нажата клавиша Break)
; over/under  - CF=0, ZF=1 (импульс слишком длинный/короткий)
; count - CF=1, ZF=0 (импульс валидный)

PERIODMIN equ 9
COUNTMIN  equ (256-60-PERIODMIN) ;    60-самый длинный период ~450Hz
EARBIT	  equ %01000000

; измерим положительный импульс  + + + D' = border color positive
measu_p:
    ld b,EARBIT
    exx
    ld a,d ; border color positive
    jr measu_c

; измерим отрицательный импульс  - - - E' = border color negative
measu_n:
    ld b,0
    exx
    ld a,e ; border color negative
measu_c:
    exx

measu:
    out (254),a
    ld c,COUNTMIN
    ; один раз при имзмерении проверяем break
    ld a,#7F
    and a	; для ZF=0
    in a,(#FE)
    rra 	; (break bit 0) ZF не изм; CF=0 при break
    ret nc	; break (ZF=0, CF=0)
    ; CF=1
.lp:
    ; CF=0 (кроме первого прохода, допустимо)
    inc c
    ret z	; ZF=1, CF=0    OVER
    ld a,#7F
    in a,(#FE)	; bit6?
    and EARBIT	; оставили бит ear
    xor b	; при B=0 не меняем A (ждём приход единицы)    CF=0 всегда
		; при B=%00100000 бит ear инвертируется (ждём приход нуля)
    jr z,.lp	; пока 0 - ждём (для обоих случаев)
    ; получен ожидаемый ear bit
    ld a,c
    sub (COUNTMIN+PERIODMIN); тут ZF=0 CF=0 только если период правильный
    jr c,.under
    scf
    ret   ; ok      CF=1, ZF=0
.under:
    sub a ; over  - CF=0, ZF=1
    ret

end_of_block:

