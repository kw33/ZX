startload:

    ld ix,#8000 ; 32768              ;30000 ; #7530
nulling:
    ld (ix),0
    inc ix
    defb #DD ; IX
    ld a,h   ; IXh
    cp #90
    jr nz,nulling

    ld ix,#8000 ; 32768
;----------------------------------------------

load:
    di
.waitpilot:
    ld a,(BORDCR)
    rrca
    rrca
    rrca
    ld (B1color),a
    ld (B0color),a ; при начальном ожидании пилота - не полосим    переделать?
    ld e,255 ; периодов пилота
.cnt:
    ld a,(B0color)
    ld b,0 ; прожуём отрицательный импульс
    call measu
    jr nc,.nc1	; не надо ? ? ?
      ;ld (ix),a
      ;inc ix ; CF not changed

    ld a,(B1color)
    ld b,EARBIT
    call measu ; будем контролировать положительный
    jr nc,.nc1
      ;ld (ix),a
      ;inc ix ; CF not changed
    cp 48 ; минимум для пилота, максимум и так ограничен
    jr c,.firstbyte
    dec e
    jr nz,.cnt
    ; cчётчик обнулился, сделаем =1
    inc e
    ; считаны все начальные пилоты, полосим
    ld a,1
    ld (B1color),a	;; из-за этих сохранений
    ld a,5		;;   счетчик меньше на 1-2  :\
    ld (B0color),a	;;   переместить?? переделать на (hl)??
    jr .cnt

.firstbyte:
    dec e ; был ли счётчик=1 ?
    jr nz,.waitpilot ; рано данные пришли

    ; далее получаем байты                     /////////////////////////////////
    ld d,a ; push
    ld a,%10101010 ; прокручивая, будем получать то 1, то 0 в CF
    ld e,a	   ; флаг для счёта полубайтов
    sub a ; a=0
    ld l,a
    ld a,d ; pop
    ; в h храним старший полубайт принимаемых данных
    ; в l - контрольную сумму
    jr .enter

.quants:
    ld a,(B1color)
    ld b,EARBIT;%00100000
    call measu
    jr nc,.err

.enter:
 ;     ld (ix),a     ; 1111 импульс
 ;     inc ix

    ; преобразовать длительность в id импульса
    ; a - длительность импульса
    and %111000 ; шесть длин импульсов, синхро-импульс сюда приходить не должен!
    rrca
    rrca
    rrca
 ;        ld (ix),a
 ;        inc ix
    ; a - id импульса (0..5)  (положительного)
    ; сохранить id импульса
    ld d,a ; d - id полож.импульса

    ; мерим длительность отрицательного импульса
    ld a,(B0color)
    ld b,0
    call measu;mea0  исп-ются abc
    jr nc,.err ;                         ??
 ;        ld (ix),a     ; 0000 импульс
 ;        inc ix
    ; преобразовать длительность в id импульса
    ; a - длительность импульса
    and %111000 ; шесть длин импульсов, синхро-импульс сюда приходить не должен!
    rrca
    rrca
    rrca
 ;        ld (ix),a
 ;        inc ix
    ; d и a - id импульса (0..5)  (положительного и отрицательного)
    ; d a вместе - это период определяющий 4 бита
    cp d
    jr z,.done ; если одинаковые - 0000..0101, d=a = искомое число
    jr nc,.n6_10 ; если a>d(d<a), то 0110..1010 (6..10) [короче|длиннeе]
    ; d>a - 1101..1111 (11..15)    a=0..4 переделываем в 15..11
    xor %1111
    jr .done
.n6_10:
    ld a,6  ; для d < a
    add a,d
.done:
    ; готово а - число (4 бита)
    rlc e
    jr nc,.secondhalf ; в а второй полубайт
    ; в а первый полубайт
    rlca
    rlca
    rlca
    rlca
    ld h,a     ; сохранили
    jr .quants
.secondhalf:
    or a,h   ; добавили ко второму первый
    ld (ix),a ; сохранить байт
    inc ix
    ; проверить, всё ли
    ;....
    jr .quants ;////////////////////////////////////////////////////////////////

    ;---------------------------------------
.nc1:
    jp z,.waitpilot ; over/under
    ; break
.break:
    ei	   ;;; EI
    ld a,(BORDCR)
    rrca
    rrca
    rrca
    out (254),a
    ld iy,5C3Ah ; на всякий=)      HL' ?
    ret

.err:
    jr nz,.break
