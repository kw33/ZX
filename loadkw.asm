; измерять продолжительность                  изменяются a b c
; отсчёт ведётся от COUNTMIN до 255
; валидный импульс включает в себя и импульс пилот-тона
; (если насчитало более 255 - слишком длинный импульс: over)
; после отсчёта вычетается COUNTMIN + PERIODMIN
; если получилось отрицательное - слишком короткий импульс: under
; b = 0 - измеряем отрицательный импульс (ear уже в нуле)
; b = %01000000 (64 = EARBIT) - измеряем положительный имп-с (ear уже в единице)
; a - цвет поребрика
; выход:
; a - длительность импульса (если она валидная, т.е. CF=1, ZF=0)
; break - CF=0, ZF=0 (нажата клавиша Break)
; over/under  - CF=0, ZF=1 (импульс слишком длинный/короткий)
; count - CF=1, ZF=0 (импульс валидный)

PERIODMIN equ 9
COUNTMIN  equ (256-60-PERIODMIN) ;    60-самый длинный период ~450Hz
EARBIT	  equ %01000000

measu_p:
    ld b,EARBIT
    exx
    ld a,d ; border color positive
    jr measu_c
measu_n:
    ld b,0
    exx
    ld a,e ; border color negative
measu_c:
    exx

measu:
    out (254),a
    ld c,COUNTMIN
    ; один раз при имзмерении проверяем break
    ld a,#7F
    and a	; для ZF=0
    in a,(#FE)
    rra 	; (break bit 0) ZF не изм; CF=0 при break
    ret nc	; break (ZF=0, CF=0)
    ; CF=1
.lp:
    ; CF=0 (кроме первого прохода, допустимо)
    inc c
    ret z	; ZF=1, CF=0    OVER
    ld a,#7F
    in a,(#FE)	; bit6?
    and EARBIT	; оставили бит ear
    xor b	; при B=0 не меняем A (ждём приход единицы)    CF=0 всегда
		; при B=%00100000 бит ear инвертируется (ждём приход нуля)
    jr z,.lp	; пока 0 - ждём (для обоих случаев)
    ; получен ожидаемый ear bit
    ld a,c
    sub (COUNTMIN+PERIODMIN); тут ZF=0 CF=0 только если период правильный
    jr c,.under
    scf
    ret   ; ok      CF=1, ZF=0
.under:
    sub a ; over  - CF=0, ZF=1
    ret

end_of_block:

