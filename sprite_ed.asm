; ------------------------------------------------------------
; ИСПРАВЛЕННАЯ ВЕРСИЯ
; Вывод спрайта 8x8 с попиксельным позиционированием
; Вход: H = Y (0-191), L = X (0-255)
; ------------------------------------------------------------

VIDEO_START     equ     $4000
SPRITE_WIDTH    equ     8
SPRITE_HEIGHT   equ     8


PutSprite:
    ; Проверка координат..???
    ld      a, h
    cp      192         ; Максимальный Y = 191
    ret     nc          ; Выход если Y >= 192
    
    push    af
    push    bc
    push    de
    push    hl
    
    ; Сохраняем оригинальные координаты
    ld      a, h        ; A = Y
    ld      b, l        ; B = X
    
    ; --------------------------------------------------------
    ; Вычисление адреса знакоместа
    ; --------------------------------------------------------
    
    ; Получаем номер строки знакомест (Y / 8)
    ld      c, a      ; C = Y (сохраняем для пиксельного сдвига)
    srl     a
    srl     a
    srl     a         ; A = Y / 8
    ld      l, a      ; L = Y / 8

    ; Определяем треть экрана (0, 1 или 2)
    ld      a, c      ; A = Y
    and     %11000000 ; Проверяем старшие биты Y
    jr      z, .first_third
    cp      $40
    jr      z, .second_third
    ; Третья треть
    ld      a, l
    add     a, $50    ; Смещение для третьей трети
    ld      l, a
    jr      .calc_horizontal
    
.second_third:
    ld      a, l
    add     a, $28    ; Смещение для второй трети
    ld      l, a
    jr      .calc_horizontal
    
.first_third:
    ; Первая треть - без смещения
    ld      a, l
    ; A уже содержит правильное значение
    
.calc_horizontal:
    ; Умножаем {Y/8} на 32 для получения смещения { по Y }
    ld      l, a   ; = 
    ld      h, 0
    add     hl, hl      ; *2
    add     hl, hl      ; *4
    add     hl, hl      ; *8
    add     hl, hl      ; *16
    add     hl, hl      ; *32
    
    ; Добавляем горизонтальное смещение (X / 8)
    ld      a, b
    srl     a
    srl     a
    srl     a           ; A = X / 8
    ld      e, a
    ld      d, 0
    add     hl, de
    
    ; Прибавляем базовый адрес экрана
    ld      de, VIDEO_START
    add     hl, de      ; HL = адрес знакоместа
    
   
    
    ; --------------------------------------------------------
    ; Пиксельный сдвиг по X
    ; --------------------------------------------------------
    ;push    hl ; Сохраняем адрес начала
    
    ld      a, b
    and     %00000111   ; A = X % 8 (сдвиг вправо)
    ld      b, a        ; B = сдвиг
    ld      c, SPRITE_HEIGHT ; C = счетчик строк
    
    ;pop     hl          ; HL = адрес знакоместа
    
    ; --------------------------------------------------------
    ; Цикл вывода строк
    ; --------------------------------------------------------
    
.line_loop:
    ; Получаем байт спрайта для текущей строки
    ld      de, SpriteData
    ld      a, SPRITE_HEIGHT
    sub     c
    ld      e, a
    ld      d, 0
    add     hl, de  ; Корректируем HL (временно)
    ex      de, hl  ; DE = адрес строки спрайта, HL = адрес экрана
    ld      a, (de) ; A = байт спрайта
    ex      de, hl  ; Меняем обратно
    
    ; Применяем сдвиг если нужно
    ld      d, a
    ld      a, b
    or      a
    jr      z, .no_shift
    
    ld      a, d
    ld      d, b        ; D = счетчик сдвига
.shift_loop:
    srl     a           ; Сдвигаем вправо
    dec     d
    jr      nz, .shift_loop
    ld      d, a
    jr      .apply_sprite
    
.no_shift:
    ld      d, a        ; D = байт спрайта без сдвига
    
.apply_sprite:
    ; Накладываем спрайт на экран
    ld      a, (hl)     ; Текущее содержимое экрана
    or      d           ; OR с байтом спрайта
    ld      (hl), a     ; Записываем обратно
    
    ; Переход к следующей строке экрана
    push    bc
    ld      bc, 32      ; Смещение до следующей строки
    add     hl, bc
    pop     bc
    
    dec     c
    jr      nz, .line_loop
    
    ; Восстанавливаем регистры и выходим
    pop     hl
    pop     de
    pop     bc
    pop     af
    ret

SpriteData:
    db  %11111111
    db  %10000001
    db  %10000001
    db  %10011001
    db  %10011001
    db  %10000001
    db  %10000001
    db  %11111111

